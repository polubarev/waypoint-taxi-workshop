using Gis.Api;
using Shared.Contracts;
using Shared.Infrastructure;
var builder=WebApplication.CreateBuilder(args);
builder.Services.AddTaxiAuth(builder.Configuration);
builder.Services.AddSingleton(new Database(builder.Configuration.GetConnectionString("Database")!));
builder.Services.AddSingleton<GisStore>();
builder.Services.AddSingleton<BrokerState>();
builder.Services.AddSingleton<IEventHandler,TripLayerConsumer>();
builder.Services.AddHostedService<EventWorker>();
var app=builder.Build();
app.UseTaxiErrors();
await app.Services.GetRequiredService<Database>().Initialize(typeof(GisStore).Assembly);
app.MapGet("/health",()=>new { service="gis",status="ok" });
app.MapGet("/ready",(BrokerState state)=>state.Connected?Results.Ok(new{status="ready"}):Results.StatusCode(503));
var api=app.MapGroup("").RequireAuthorization().AddEndpointFilter<ContractFilter>();
api.MapGet("/zones",(GisStore zones)=>zones.Zones());
api.MapPost("/validate",(TripValidationRequest request,GisStore zones)=>zones.Validate(request));
api.MapGet("/trips",(GisStore zones)=>zones.LiveTrips()).RequireAuthorization(p=>p.RequireRole(Roles.Dispatcher));
api.MapPost("/zones",async(ZoneRequest request,GisStore zones)=>Results.Created("/gis/zones",new{id=await zones.Save(null,request)})).RequireAuthorization(p=>p.RequireRole(Roles.GisAdmin));
api.MapPut("/zones/{id:guid}",async(Guid id,ZoneRequest request,GisStore zones)=>new{id=await zones.Save(id,request)}).RequireAuthorization(p=>p.RequireRole(Roles.GisAdmin));
api.MapDelete("/zones/{id:guid}",async(Guid id,Database db)=>await db.Execute("DELETE FROM zones WHERE id=$1",id)>0?Results.NoContent():Results.NotFound()).RequireAuthorization(p=>p.RequireRole(Roles.GisAdmin));
app.MapOperations();
app.Run();
